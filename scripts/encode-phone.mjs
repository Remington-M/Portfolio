#!/usr/bin/env node
/**
 * Draw a second, smaller copy of each clip for phones.
 *
 * `public/media/<slug>/<name>.mp4` gains `public/media/<slug>/phone/<name>.mp4`.
 * The main encode holds the longest side to 1920, which is right for a viewer
 * a thousand points wide on a 2x display and four times the pixels a phone
 * can show: there the viewer is at most ~366 points across, so a 1920-wide
 * desktop recording is drawn at a fifth of its size and the rest is data
 * the visitor paid for on a mobile connection and never saw.
 *
 *   node scripts/encode-phone.mjs            # anything out of date
 *   node scripts/encode-phone.mjs --force    # all of it again
 *   node scripts/encode-phone.mjs mys        # one project
 *
 * Run it after `npm run media`. It reads the clips that script wrote rather
 * than the raw exports, so it works from a checkout alone — `media-source/`
 * is not in the repository — and inherits the crops for free. Shrinking an
 * already-encoded clip costs a generation, which at well under half the
 * pixels is not visible.
 *
 * It writes `lib/renditions.generated.ts`, listing the clips it kept a phone
 * copy of. The app reads that list rather than deriving the path, for the
 * same reason the posters have one: a derived path to a file that was never
 * written is a 404, and a static export has nothing to check with.
 */
import { execFile } from "node:child_process";
import { mkdir, readdir, rm, stat, writeFile } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { promisify } from "node:util";

const run = promisify(execFile);
const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const MEDIA = join(ROOT, "public", "media");

/**
 * The longest side of a phone copy.
 *
 * A portrait recording fills the viewer's height, about 630 points, so 1280
 * is 2x there; a wide one spans ~366 points, so 1280 is better than 3x. Two
 * device pixels per point is where moving footage stops looking any sharper.
 */
const MAX_SIDE = 1280;
/** A step softer than the main encode's 21, and half its ceiling. */
const CRF = 23;
const MAXRATE = "3500k";
const BUFSIZE = "7M";
/**
 * A copy has to earn its place. Flat UI compresses to almost nothing at any
 * size, and a second file that saves a tenth is a second file to keep in
 * step for nothing — anything not at least this much smaller is dropped and
 * the phone plays the main clip.
 */
const KEEP_BELOW = 0.75;

const SCALE =
  `scale=w=min(${MAX_SIDE}\\,iw):h=min(${MAX_SIDE}\\,ih)` +
  `:force_original_aspect_ratio=decrease:force_divisible_by=2`;

const size = async (f) => (await stat(f).catch(() => null))?.size ?? -1;
const mtime = async (f) => (await stat(f).catch(() => null))?.mtimeMs ?? -1;

const argv = process.argv.slice(2);
const force = argv.includes("--force");
const only = argv.filter((a) => !a.startsWith("--"));

const slugs = (await readdir(MEDIA, { withFileTypes: true }))
  .filter((e) => e.isDirectory())
  .map((e) => e.name)
  .sort();

const kept = [];
let before = 0;
let after = 0;

for (const slug of slugs) {
  const dir = join(MEDIA, slug);
  const out = join(dir, "phone");
  const clips = (await readdir(dir)).filter((f) => f.endsWith(".mp4")).sort();
  if (clips.length === 0) continue;
  await mkdir(out, { recursive: true });
  const touch = only.length === 0 || only.includes(slug);
  console.log(`\n${slug}`);

  for (const clip of clips) {
    const src = join(dir, clip);
    const dst = join(out, clip);
    const url = `/media/${slug}/${clip}`;
    const full = await size(src);

    if (touch && (force || (await mtime(dst)) < (await mtime(src)))) {
      await run(
        "ffmpeg",
        [
          "-hide_banner", "-loglevel", "error", "-y",
          "-i", src,
          "-map", "0:v:0", "-an", "-sn", "-dn",
          "-vf", SCALE,
          "-c:v", "libx264", "-profile:v", "high", "-pix_fmt", "yuv420p",
          "-preset", "slow", "-crf", String(CRF),
          "-maxrate", MAXRATE, "-bufsize", BUFSIZE,
          "-movflags", "+faststart",
          dst,
        ],
        { maxBuffer: 1 << 24 },
      );
    }

    const small = await size(dst);
    const kb = (n) => `${(n / 1024).toFixed(0)}KB`.padStart(7);
    if (small < 0) {
      console.log(`  · ${clip.padEnd(40)} no phone copy`);
    } else if (small > full * KEEP_BELOW) {
      // Not worth a second file. Removed, so the folder holds only what the
      // manifest names.
      await rm(dst);
      console.log(`  · ${clip.padEnd(40)} ${kb(full)} -> ${kb(small)}  not worth it, dropped`);
    } else {
      kept.push(url);
      before += full;
      after += small;
      console.log(`  ✓ ${clip.padEnd(40)} ${kb(full)} -> ${kb(small)}`);
    }
  }
}

const manifest =
  `/**\n` +
  ` * Generated by \`npm run media:phone\`. Do not edit.\n` +
  ` *\n` +
  ` * Clips that have a smaller copy for phones, at \`phone/<name>.mp4\` beside\n` +
  ` * them. See \`scripts/encode-phone.mjs\`.\n` +
  ` */\n` +
  `export const CLIPS_WITH_PHONE = new Set<string>([\n` +
  kept.map((c) => `  ${JSON.stringify(c)},`).join("\n") +
  (kept.length ? "\n" : "") +
  `]);\n`;
await writeFile(join(ROOT, "lib/renditions.generated.ts"), manifest);

const mb = (n) => (n / 1e6).toFixed(1);
console.log(
  `\n${kept.length} phone copies: ${mb(before)}MB of clips -> ${mb(after)}MB on a phone.`,
);
